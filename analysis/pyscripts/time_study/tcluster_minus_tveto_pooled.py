#!/usr/bin/env python3
"""Pooled V1-V4 t_cluster - t_veto: BEST recipe per counter, per-counter alignment, merged fit (reuses the scan's loaders/fits).

BEST recipe: calibrated MF cluster time (energy-weighted member mean, time_calib.json subtracted), E>100 MeV, seed amp >= 500 ADC,
no Moller, veto pulse within +-10 ns of the first-pass mode with integral > 2000 (largest integral), 0.2 ns bins, Gauss+const +-5 ns.
Alignment: mu_k (fit of counter k) is subtracted and the V1 mean added back, i.e. all counters are aligned to the V1 mean.
Merged = concatenation of the four per-counter dt arrays (an event can enter once per counter that has a pulse).
Robust = half the 16-84 % range of the hits within +-5 ns of the mode (the scan's estimator).

  python3 tcluster_minus_tveto_pooled.py --scratch SCRATCH [--sample SLUG ...]
"""
import argparse
from pathlib import Path

import numpy as np

import tcluster_minus_tveto_scan as sc

HERE = sc.HERE
BIN = 0.2   # ns, histogram / fit bin of this script (the scan uses 0.25)


def fit_row(dt):
    """Same as sc.fit_row (mode, Gauss+const +-5 ns, robust = half 16-84 % range in +-5 ns) but on BIN-wide bins."""
    dt = dt[np.isfinite(dt)]
    R = dict(N=len(dt), Npk=0, mu=np.nan, sig=np.nan, err=np.nan, rob=np.nan)
    if len(dt) < 30:
        return R
    mode = sc.find_mode(dt)
    w = dt[np.abs(dt - mode) <= sc.WIN]
    R["Npk"] = len(w)
    if len(w) >= 10:
        R["rob"] = 0.5 * (np.percentile(w, 84) - np.percentile(w, 16))
    h, e = np.histogram(dt, bins=np.arange(mode - sc.WIN, mode + sc.WIN + 1e-9, BIN))
    x = 0.5 * (e[:-1] + e[1:])
    try:
        p, cv = sc.curve_fit(sc.gauss_c, x, h, p0=(max(h.max() - np.median(h), 1), mode, 1.0, np.median(h)), sigma=np.sqrt(np.maximum(h, 1.0)),
                             bounds=([0, mode - sc.WIN, 0.05, 0], [np.inf, mode + sc.WIN, sc.WIN, np.inf]), maxfev=2000)
        R.update(mu=p[1], sig=abs(p[2]), err=np.sqrt(cv[2, 2]))
    except Exception:
        pass
    return R
DEF = ["0p73GeV_H2", "2p24GeV_H2", "3p49GeV_H2"]


def per_counter(S):
    tcl = np.where(sc.sel_mask(S, "e100+A500+noMoller"), sc.cl_wmmf_cal(S), np.nan)
    dts = {}
    for k in (1, 2, 3, 4):
        tv0, _ = sc.pick_veto(S["veto"], S["ev"], tcl, [k])
        d0 = tcl - tv0
        g = sc.find_mode(d0[np.isfinite(d0)]) if np.isfinite(d0).sum() > 30 else 0.0
        tv, _ = sc.pick_veto(S["veto"], S["ev"], tcl, [k], imin=2000, gate=g)
        dt = (tcl - tv)
        dts[k] = dt[np.isfinite(dt)]
    return dts


def panel(ax, dt, R, title):
    mode = sc.find_mode(dt)
    h, e = np.histogram(dt, bins=np.arange(mode - 8, mode + 8, BIN))
    ax.stairs(h, e, fill=True, color="C0", alpha=0.6)
    if np.isfinite(R["mu"]):
        hh, ee = np.histogram(dt, bins=np.arange(mode - sc.WIN, mode + sc.WIN + 1e-9, BIN))
        p = sc.curve_fit(sc.gauss_c, 0.5 * (ee[1:] + ee[:-1]), hh, p0=(max(hh.max() - np.median(hh), 1), R["mu"], R["sig"], np.median(hh)),
                         sigma=np.sqrt(np.maximum(hh, 1.0)), maxfev=2000)[0]
        xs = np.linspace(R["mu"] - sc.WIN, R["mu"] + sc.WIN, 200)
        ax.plot(xs, sc.gauss_c(xs, *p), "r-")
    ax.set_title(title); ax.set_xlabel("t_cluster - t_veto (ns)"); ax.set_ylabel("events / 0.2 ns")
    ax.text(0.03, 0.95, f"N = {R['N']}\n$\\mu$ = {R['mu']:.2f} ns\n$\\sigma$ = {R['sig']:.2f} +- {R['err']:.2f} ns\nrobust {R['rob']:.2f} ns",
            transform=ax.transAxes, va="top", fontsize=9)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--scratch", required=True)
    ap.add_argument("--sample", nargs="*", default=DEF)
    ap.add_argument("--table", default=str(HERE / "tables/pooled_vetos.md"))
    ap.add_argument("--figdir", default=str(HERE / "figures"))
    a = ap.parse_args()
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    md = ["# Pooled vetos V1-V4", "",
          "Generated by `tcluster_minus_tveto_pooled.py`. BEST recipe per counter (wmMF_cal, e100+A500+noMoller, gate +-10 ns, integral > 2000, largest integral), "
          "fit 0.2 ns bins, Gauss + constant +-5 ns; robust = half the 16-84 % range within +-5 ns of the mode. Alignment: mu_k subtracted, V1 mean added back. "
          "Merged = concatenation of the per-counter entries (one event can appear in several counters).", "",
          "| sample | row | mu (ns) | sigma (ns) | sigma err | robust (ns) | N | N in +-5 ns |", "|---|---|---|---|---|---|---|---|"]
    for slug in a.sample:
        S = sc.load_sample(a.scratch, slug)
        dts = per_counter(S)
        Rk = {k: fit_row(dts[k]) for k in dts}
        ref = Rk[1]["mu"]
        al = {k: dts[k] - Rk[k]["mu"] + ref if np.isfinite(Rk[k]["mu"]) else dts[k][:0] for k in dts}
        Ral = {k: fit_row(al[k]) for k in al}
        Rm = fit_row(np.concatenate(list(al.values())))
        Ru = fit_row(np.concatenate(list(dts.values())))
        for k in (1, 2, 3, 4):
            r = Rk[k]; md.append(f"| {slug} | V{k} | {r['mu']:.2f} | {r['sig']:.3f} | {r['err']:.3f} | {r['rob']:.3f} | {r['N']} | {r['Npk']} |")
        for lab, r in (("merged aligned", Rm), ("merged unaligned", Ru)):
            md.append(f"| {slug} | {lab} | {r['mu']:.2f} | {r['sig']:.3f} | {r['err']:.3f} | {r['rob']:.3f} | {r['N']} | {r['Npk']} |")
        print(f"== {slug}: " + ", ".join(f"V{k} {Rk[k]['sig']:.3f} (N={Rk[k]['N']})" for k in Rk))
        print(f"   merged aligned {Rm['sig']:.3f}+-{Rm['err']:.3f} robust {Rm['rob']:.3f} N={Rm['N']} | unaligned {Ru['sig']:.3f}+-{Ru['err']:.3f} robust {Ru['rob']:.3f} N={Ru['N']}")
        fig, axs = plt.subplots(2, 3, figsize=(14, 7))
        for k, ax in zip((1, 2, 3, 4), axs.flat):
            panel(ax, al[k], Ral[k], f"V{k} aligned")
        panel(axs.flat[4], np.concatenate(list(al.values())), Rm, "merged V1-V4 (aligned)")
        panel(axs.flat[5], np.concatenate(list(dts.values())), Ru, "merged V1-V4 (unaligned)")
        fig.suptitle(f"{slug}: pooled vetos, BEST recipe (0.2 ns bins, Gauss+const +-5 ns)")
        fig.tight_layout(); fig.savefig(Path(a.figdir) / f"tcluster_minus_tveto_{slug}_pooled.png", dpi=120); plt.close(fig)
    Path(a.table).write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
