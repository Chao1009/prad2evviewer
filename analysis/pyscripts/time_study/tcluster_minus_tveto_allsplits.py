#!/usr/bin/env python3
"""All-splits version of tcluster_minus_tveto_pooled.py: the identical BEST recipe on every split of one run, entries concatenated.

Per-split loading / selection / veto pick / fit are those of tcluster_minus_tveto_pooled.py (same functions). Alignment uses one mu_k per
run (fit of the concatenated counter-k histogram, V1 mean added back) unless the per-split mu_k scatter is well above its fit error
(chi2/ndf of mu_k over splits > DRIFT_CHI2), in which case mu_k is taken per split. mu_k per split is tabulated either way.

  python3 tcluster_minus_tveto_allsplits.py --scratch SCRATCH [--sample SLUG ...]
SCRATCH holds ct_0p73GeV_H2_e100/, ct_3p49GeV_H2_e100/ (benchmark outputs <run>_<split>/ of the e100 chain, from crosstalk_study) and
ts_025320_e100/ (all splits of 2.24 GeV run 25320); veto dumps are read from output/module_timing_20261030/dump/<run>_<split>.npz.
"""
import argparse
from pathlib import Path

import numpy as np

import tcluster_minus_tveto_scan as sc
import tcluster_minus_tveto_pooled as pl

HERE = sc.HERE
RUNS = {"0p73GeV_H2": ("ct_0p73GeV_H2_e100", 24590), "2p24GeV_H2": ("ts_025320_e100", 25320), "3p49GeV_H2": ("ct_3p49GeV_H2_e100", 24503)}
DRIFT_CHI2 = 2.0   # chi2/ndf of mu_k(split) about its weighted mean above which the alignment is done per split


def splits_of(scratch, d, run):
    """Splits with a completed benchmark output (rc 0, pulse.npz, cluster TSV) and a veto dump."""
    out = []
    for p in sorted((Path(scratch) / d).glob(f"{run:06d}_*")):
        rc = (p / "rc").read_text().split()[0] if (p / "rc").exists() else "missing"
        ok = rc in ("0", "rc=0") and (p / "pulse.npz").exists() and (p / "result_clusters.tsv").exists() and (sc.DUMP / f"{p.name}.npz").exists()
        if ok:
            out.append(p.name)
        else:
            print(f"[WARN] skipping {p.name}: rc={rc}")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--scratch", required=True)
    ap.add_argument("--sample", nargs="*", default=list(RUNS))
    ap.add_argument("--table", default=str(HERE / "tables/pooled_vetos_allsplits.md"))
    ap.add_argument("--figdir", default=str(HERE / "figures"))
    a = ap.parse_args()
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    md = ["# Pooled vetos V1-V4, all splits of one run", "",
          "Generated by `tcluster_minus_tveto_allsplits.py`. BEST recipe of `pooled_vetos.md` (wmMF_cal, e100+A500+noMoller, gate +-10 ns, integral > 2000, "
          "largest integral, 0.2 ns bins, Gauss + constant +-5 ns; robust = half the 16-84 % range within +-5 ns of the mode) applied to every split of the run "
          "and concatenated. Alignment: mu_k subtracted, V1 mean added back; mu_k is one value per run unless stated. Merged = concatenation of the per-counter "
          "entries (one event can appear in several counters).", ""]
    tab = ["| sample (run) | row | mu_run (ns) | sigma (ns) | sigma err | robust (ns) | N | N in +-5 ns |", "|---|---|---|---|---|---|---|---|"]
    drift = ["", "## mu_k per split (ns, +- sigma/sqrt(N in +-5 ns), the centroid error; N per split in brackets)", "",
             "| sample (run) | split | V1 | V2 | V3 | V4 |", "|---|---|---|---|---|---|"]
    summ = ["", "## mu_k scatter over splits", "", "| sample (run) | counter | splits | mean mu (ns) | rms over splits (ns) | mean centroid err (ns) | chi2/ndf about weighted mean |", "|---|---|---|---|---|---|---|"]
    verdict = []
    ev_used = ["", "## Splits and events used", "", "| sample (run) | splits (first..last) | selected clusters (e100, A500, noMoller) | entries V1 / V2 / V3 / V4 |", "|---|---|---|---|"]
    for slug in a.sample:
        d, run = RUNS[slug]
        sps = splits_of(a.scratch, d, run)
        per = {}                               # split -> {k: dt}
        nsel = 0                               # selected single clusters (e100 + A500 + noMoller, finite cluster time), all splits
        for rs in sps:
            sc.SAMPLES["_as"] = (d, rs, "")
            S = sc.load_sample(a.scratch, "_as")
            per[rs] = pl.per_counter(S)
            nsel += int(np.sum(sc.sel_mask(S, "e100+A500+noMoller") & np.isfinite(sc.cl_wmmf_cal(S))))
        dts = {k: np.concatenate([per[rs][k] for rs in sps]) for k in (1, 2, 3, 4)}
        # per-split mu_k
        Rs = {rs: {k: pl.fit_row(per[rs][k]) for k in (1, 2, 3, 4)} for rs in sps}
        for rs in sps:
            drift.append(f"| {slug} ({run}) | {rs[7:]} | " + " | ".join(
                f"{Rs[rs][k]['mu']:.2f} +- {Rs[rs][k]['sig'] / np.sqrt(max(Rs[rs][k]['Npk'], 1)):.2f} ({Rs[rs][k]['N']})" if np.isfinite(Rs[rs][k]["mu"]) else f"n/a ({Rs[rs][k]['N']})" for k in (1, 2, 3, 4)) + " |")
        worst = 0.0
        for k in (1, 2, 3, 4):
            mu = np.array([Rs[rs][k]["mu"] for rs in sps]); er = np.array([Rs[rs][k]["err"] for rs in sps])
            m = np.isfinite(mu) & np.isfinite(er) & (er > 0) & (np.array([Rs[rs][k]["N"] for rs in sps]) >= 30)
            # mu error: sigma_fit err is not the mu error; use sigma/sqrt(Npk) as the centroid error
            sg = np.array([Rs[rs][k]["sig"] for rs in sps]); npk = np.array([max(Rs[rs][k]["Npk"], 1) for rs in sps])
            me = sg / np.sqrt(npk)
            m &= np.isfinite(me) & (me > 0)
            w = 1 / me[m] ** 2
            mw = np.sum(w * mu[m]) / np.sum(w)
            chi = np.sum(w * (mu[m] - mw) ** 2) / max(m.sum() - 1, 1)
            worst = max(worst, chi)
            summ.append(f"| {slug} ({run}) | V{k} | {m.sum()} | {np.mean(mu[m]):.2f} | {np.std(mu[m], ddof=1):.3f} | {np.mean(me[m]):.3f} | {chi:.2f} |")
        per_split = worst > DRIFT_CHI2
        mode = "per split" if per_split else "per run"
        verdict.append(f"{slug}: mu_k alignment {mode} (worst chi2/ndf {worst:.2f}; centroid error = sigma/sqrt(N in +-5 ns))")
        # alignment: per run (one mu_k from the concatenated histogram) and per split (mu_k of each split, V1 run-mean added back)
        Rk = {k: pl.fit_row(dts[k]) for k in dts}
        al_run = {k: dts[k] - Rk[k]["mu"] + Rk[1]["mu"] if np.isfinite(Rk[k]["mu"]) else dts[k][:0] for k in dts}
        ref = np.mean([Rs[rs][1]["mu"] for rs in sps if np.isfinite(Rs[rs][1]["mu"])])
        al_spl = {k: np.concatenate([per[rs][k] - Rs[rs][k]["mu"] + ref for rs in sps if np.isfinite(Rs[rs][k]["mu"])]) for k in dts}
        al = al_spl if per_split else al_run
        Rm_alt = pl.fit_row(np.concatenate(list((al_run if per_split else al_spl).values())))
        Ral = {k: pl.fit_row(al[k]) for k in al}
        Rm = pl.fit_row(np.concatenate(list(al.values())))
        Ru = pl.fit_row(np.concatenate(list(dts.values())))
        lab = f"{slug} ({run}, {len(sps)} splits)"
        ev_used.append(f"| {slug} ({run}) | {len(sps)} ({sps[0][7:]}..{sps[-1][7:]}) | {nsel} | " + " / ".join(str(Rk[k]["N"]) for k in (1, 2, 3, 4)) + " |")
        for k in (1, 2, 3, 4):
            r = Ral[k]
            tab.append(f"| {lab} | V{k} | {Rk[k]['mu']:.2f} | {r['sig']:.3f} | {r['err']:.3f} | {r['rob']:.3f} | {r['N']} | {r['Npk']} |")
        alt = "merged aligned (per-run mu_k)" if per_split else "merged aligned (per-split mu_k)"
        for l, r in (("merged aligned", Rm), ("merged unaligned", Ru), (alt + ", for comparison", Rm_alt)):
            tab.append(f"| {lab} | {l} | {r['mu']:.2f} | {r['sig']:.3f} | {r['err']:.3f} | {r['rob']:.3f} | {r['N']} | {r['Npk']} |")
        print(f"== {slug} run {run}: {len(sps)} splits {sps[0][7:]}..{sps[-1][7:]}; alignment {mode}")
        print("   " + ", ".join(f"V{k} {Ral[k]['sig']:.3f} (N={Ral[k]['N']})" for k in Ral))
        print(f"   merged aligned {Rm['sig']:.3f}+-{Rm['err']:.3f} robust {Rm['rob']:.3f} N={Rm['N']} | unaligned {Ru['sig']:.3f}+-{Ru['err']:.3f} robust {Ru['rob']:.3f} N={Ru['N']}")
        for line in summ[-4:]:
            print("   " + line)
        fig, axs = plt.subplots(2, 3, figsize=(14, 7))
        for k, ax in zip((1, 2, 3, 4), axs.flat):
            pl.panel(ax, al[k], Ral[k], f"V{k} aligned")
        pl.panel(axs.flat[4], np.concatenate(list(al.values())), Rm, "merged V1-V4 (aligned)")
        pl.panel(axs.flat[5], np.concatenate(list(dts.values())), Ru, "merged V1-V4 (unaligned)")
        fig.suptitle(f"{slug} run {run}: all {len(sps)} splits, BEST recipe (0.2 ns bins, Gauss+const +-5 ns, mu_k {mode})")
        fig.tight_layout(); fig.savefig(Path(a.figdir) / f"tcluster_minus_tveto_{slug}_pooled_allsplits.png", dpi=120); plt.close(fig)
    Path(a.table).write_text("\n".join(md + tab + ev_used + summ + [""] + ["Alignment used: " + "; ".join(verdict)] + drift) + "\n")


if __name__ == "__main__":
    main()
